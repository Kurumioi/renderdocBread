"""Generate the GUI's offline catalog from the authoritative AgentHost definitions."""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "replaylab/src"))


def generate() -> str:
    from replaylab_agent.catalog import PRESETS
    from replaylab_agent.process_env import RESERVED_CREDENTIAL_ENV, _MANAGED_VENDOR_STATE_DIRS

    # Extract simple schema constants without importing model SDKs at build time.
    constants = {}
    for node in ast.parse((ROOT / "replaylab/src/replaylab_agent/conversation.py").read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                constants[node.targets[0].id] = node.value.value
            if node.targets[0].id == "SUPPORTED_CONVERSATION_SCHEMAS":
                schemas = [constants[item.id] for item in node.value.elts]

    rows = []
    for preset in PRESETS:
        rows.append({
            "id": preset.id, "title": preset.title, "kind": preset.kind,
            "executionMode": "model-api" if preset.kind == "model" else "agent-protocol",
            "loopOwner": "deepagents" if preset.kind == "model" else "vendor",
            "configurationMode": preset.configuration_mode, "protocol": preset.protocol,
            "auth": preset.auth, "authenticationUi": preset.authentication_ui,
            "supportsModelDiscovery": preset.supports_model_discovery,
            "supportsManagedLogin": preset.subscription_login_mode != "none",
            "subscriptionLoginMode": preset.subscription_login_mode,
            "interactiveTerminalRequired": preset.subscription_login_mode == "terminal",
            "installHint": preset.install_hint, "defaultModel": "", "baseUrl": preset.base_url,
            "apiKeyEnv": preset.api_key_env, "command": list(preset.command), "note": preset.note,
            "declaredCapabilities": sorted(preset.declared_capabilities),
        })
    payload = {"presets": rows, "runInputSchemas": schemas,
               "reservedCredentialEnv": sorted(RESERVED_CREDENTIAL_ENV),
               "vendorStateDirectories": {"codex": "codex", "cursor-acp": "cursor",
                                          "codebuddy-acp": "codebuddy", **_MANAGED_VENDOR_STATE_DIRS}}
    encoded = json.dumps(payload, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    return ("// Generated by util/ai/generate_provider_catalog.py. Do not edit.\n"
            "// i18n-ignore: Serialized protocol data; provider text is registered in AIAssistant.cpp.\n"
            'static const char AIProviderCatalogJSON[] =\n' +
            '\n'.join('R"bread(' + encoded[index:index + 4096] + ')bread"' for index in range(0, len(encoded), 4096)) + ';\n')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "qrenderdoc/Windows/AI/AIProviderCatalog.inc"
    content = generate()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("Offline AI catalog is stale; run util/ai/generate_provider_catalog.py")
        print("Offline AI provider catalog is current")
    else:
        target.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
